"""Captures de chaque page (mode démo, 390×844 ×2) pour les slides explicatives."""
import asyncio, os, sys
from playwright.async_api import async_playwright
BASE = sys.argv[1]; OUT = sys.argv[2]
os.makedirs(OUT, exist_ok=True)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2)
        pg = await ctx.new_page()
        async def clic(t, exact=False, s=1000): await pg.get_by_text(t, exact=exact).filter(visible=True).first.click(); await pg.wait_for_timeout(s)
        async def photo(n): await pg.screenshot(path=f'{OUT}/{n}.png')
        async def bas(): await pg.mouse.move(195, 500); await pg.mouse.wheel(0, 2500); await pg.wait_for_timeout(900)
        # client
        await pg.goto(BASE + '/connexion'); await pg.wait_for_timeout(2000); await photo('01-connexion')
        await pg.get_by_placeholder('Ex. Sophie').fill('Bertrand'); await pg.get_by_placeholder('0696 12 34 56').fill('0696123456')
        await clic('Recevoir le code'); await pg.get_by_placeholder('••••••').fill('123456'); await clic('Valider', s=1800)
        await photo('02-accueil')
        await pg.goto(BASE + '/carte'); await pg.wait_for_timeout(1800); await photo('03-carte')
        await pg.goto(BASE + '/'); await pg.wait_for_timeout(1200); await clic('Étal de', s=1500)
        await pg.get_by_label('Ajouter Thon jaune').filter(visible=True).first.click(); await pg.wait_for_timeout(500)
        await pg.get_by_label('Plus').filter(visible=True).first.click(); await pg.wait_for_timeout(800); await photo('04-etal')
        await pg.get_by_text('Voir mon panier').filter(visible=True).last.click(); await pg.wait_for_timeout(1200); await photo('05-panier')
        await clic('Réserver et payer', s=2500); await photo('06-bon')
        await bas(); await photo('07-suivi')
        await pg.mouse.wheel(0, -2500); await pg.wait_for_timeout(600)
        await clic('Message', exact=True, s=1500)
        await pg.get_by_placeholder('Écrire à', exact=False).filter(visible=True).first.fill('Je passe vers 10 h, mon numéro 0696 12 34 56')
        await pg.get_by_label('Envoyer', exact=True).filter(visible=True).first.click(); await pg.wait_for_timeout(3500); await photo('08-messagerie')
        await clic('Signaler un problème', s=1200); await photo('09-signaler'); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(500)
        if await pg.get_by_label('Fermer').filter(visible=True).count(): await pg.get_by_label('Fermer').filter(visible=True).first.click(); await pg.wait_for_timeout(600)
        await pg.get_by_label('Appeler', exact=True).filter(visible=True).first.click(); await pg.wait_for_timeout(3500); await photo('10-appel')
        await pg.get_by_label('Raccrocher').first.click(); await pg.wait_for_timeout(2500)
        await pg.goto(BASE + '/bons'); await pg.wait_for_timeout(1500); await photo('11-mes-bons')
        await pg.goto(BASE + '/compte'); await pg.wait_for_timeout(1500); await photo('12-compte')
        # pêcheur
        await clic('Me déconnecter')
        await pg.get_by_text('Pêcheur', exact=True).filter(visible=True).click(); await pg.wait_for_timeout(500)
        await pg.get_by_placeholder('0696 12 34 56').fill('0696999999'); await clic('Recevoir le code')
        await pg.get_by_placeholder('••••••').fill('123456'); await clic('Valider', s=1200)
        await pg.get_by_placeholder('Ex. Jean-Marc').fill('Louis'); await pg.get_by_placeholder('Ex. Yole Bèl Lanmè').fill('Ti Moun')
        await pg.get_by_placeholder('Ex. FF 890414').fill('FF 123456'); await pg.get_by_placeholder('Numéro d’identification du marin').fill('AB123456')
        await pg.wait_for_timeout(500); await bas(); await photo('13-inscription-pecheur')
        await clic('Envoyer mon dossier', s=1500); await photo('14-verification')
        await clic('Démo : simuler la vérification'); await clic('Ouvrir mon compte de paiement'); await clic('Publier mon premier arrivage', s=1200)
        await clic('+ Ajouter une espèce'); await clic('Thon jaune', exact=True)
        await clic('+ Ajouter une espèce'); await clic('Vivaneau', exact=True, s=1200); await photo('15-arrivage')
        await clic('Mettre en vente', s=2000)
        await pg.goto(BASE + '/reservations'); await pg.wait_for_timeout(1500); await photo('16-reservations')
        await pg.goto(BASE + '/pesee/R-27'); await pg.wait_for_timeout(1500)
        await pg.get_by_placeholder('6 chiffres', exact=False).fill('482615'); await pg.wait_for_timeout(1500); await photo('17-pesee')
        await pg.goto(BASE + '/arrivage'); await pg.wait_for_timeout(1200); await clic('Besoins pros', exact=True, s=1500); await photo('18-besoins-pros')
        # pro
        await pg.goto(BASE + '/compte'); await pg.wait_for_timeout(1000); await clic('Me déconnecter')
        await pg.get_by_text('Professionnel', exact=True).filter(visible=True).click(); await pg.wait_for_timeout(800); await photo('19-connexion-pro')
        await pg.get_by_placeholder('0696 12 34 56').fill('0696555555'); await clic('Recevoir le code')
        await pg.get_by_placeholder('••••••').fill('123456'); await clic('Valider', s=1500); await photo('20-inscription-pro')
        await b.close()
asyncio.run(main())
